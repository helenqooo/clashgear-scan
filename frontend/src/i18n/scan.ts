export function useScan() {
  const { lang } = useLang()
  const tag = localeTag(lang)
  return {
    lang: (lang === 'tr' ? 'tr' : 'en') as 'tr' | 'en',
    t: lang === 'tr' ? scanTr : scanEn,
    num: (n: number) => n.toLocaleString(tag),
    date: (when: string | number) => new Date(when).toLocaleString(tag),
  }
}
